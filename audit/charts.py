"""
Headline chart #1: cohort retention heatmap (real) beside the real-vs-null
band overlay. Regenerated by `make charts`, not exported by hand from a
notebook.

Left panel: entry_month x months_since_entry retention_rate, straight
from the fct_cohort_retention mart.

Right panel: the pooled retention curve (descriptive only -- the
pre-committed decision lives in audit/retention_null.py and is not
re-derived here) against a 20-redraw Null A' band, so a reader can see at
a glance why the audit concluded the shape is intensity-driven.
"""

import duckdb
import matplotlib.pyplot as plt
import numpy as np
import polars as pl

from audit.retention_null import (
    DB_PATH,
    SEED,
    assign_entry_cohorts,
    build_span_anchored_null,
    compute_retention_curve,
    load_real_fill_events,
)

FIG_PATH = "reports/figures/headline_retention.png"
MAX_K = 16
N_REDRAWS = 20


def load_heatmap_grid(con):
    return con.execute("""
        select entry_month, months_since_entry, retention_rate
        from main_marts.fct_cohort_retention
        order by entry_month, months_since_entry
    """).pl()


def plot_heatmap(ax, grid):
    cohorts = sorted(grid["entry_month"].unique().to_list())
    max_k = int(grid["months_since_entry"].max())
    matrix = np.full((len(cohorts), max_k + 1), np.nan)
    cohort_idx = {c: i for i, c in enumerate(cohorts)}
    for row in grid.iter_rows(named=True):
        matrix[cohort_idx[row["entry_month"]], row["months_since_entry"]] = row["retention_rate"]

    im = ax.imshow(matrix, aspect="auto", cmap="YlGnBu", vmin=0, vmax=100)
    ax.set_yticks(range(len(cohorts)))
    ax.set_yticklabels([c.strftime("%Y-%m") for c in cohorts], fontsize=8)
    ax.set_xticks(range(0, max_k + 1, 2))
    ax.set_xlabel("Months since entry")
    ax.set_title("Cohort retention (real)")
    plt.colorbar(im, ax=ax, label="Retention rate (%)", fraction=0.046, pad=0.04)


def plot_overlay(ax, real_curve, null_band):
    k = real_curve["months_since_entry"].to_list()
    real = real_curve["retention_rate"].to_list()
    nk = null_band["months_since_entry"].to_list()
    med = null_band["null_median"].to_list()
    p5 = null_band["null_p5"].to_list()
    p95 = null_band["null_p95"].to_list()

    ax.fill_between(nk, p5, p95, alpha=0.25, label="Null band (5th-95th, 20 redraws)")
    ax.plot(nk, med, linestyle="--", label="Null median")
    ax.plot(k, real, marker="o", markersize=3, label="Real")
    ax.axvline(6, color="gray", linewidth=0.8, linestyle=":")
    ax.set_xlabel("Months since entry")
    ax.set_ylabel("Pooled retention rate (%)")
    ax.set_title("Real vs. null retention curve")
    ax.legend(fontsize=8)


def main():
    con = duckdb.connect(DB_PATH, read_only=True)

    fills = load_real_fill_events(con)
    real_cohorts = assign_entry_cohorts(fills)
    real_curve = compute_retention_curve(fills, real_cohorts, max_k=MAX_K)

    null_curves = []
    for seed in range(SEED, SEED + N_REDRAWS):
        redrawn = build_span_anchored_null(fills, seed=seed)
        null_cohorts = assign_entry_cohorts(redrawn)
        null_curves.append(compute_retention_curve(redrawn, null_cohorts, max_k=MAX_K))
    combined = pl.concat(null_curves)
    null_band = (
        combined.group_by("months_since_entry")
        .agg(
            pl.col("retention_rate").median().alias("null_median"),
            pl.col("retention_rate").quantile(0.05).alias("null_p5"),
            pl.col("retention_rate").quantile(0.95).alias("null_p95"),
        )
        .sort("months_since_entry")
    )

    grid = load_heatmap_grid(con)

    fig, axes = plt.subplots(1, 2, figsize=(14, 6))
    plot_heatmap(axes[0], grid)
    plot_overlay(axes[1], real_curve, null_band)
    fig.tight_layout()
    fig.savefig(FIG_PATH, dpi=150)
    print(f"Saved {FIG_PATH}")
    con.close()


if __name__ == "__main__":
    main()
